"""The Encoding manifest (spec A6): C# is the only encoder; Python reads its manifest to size the network.

The manifest is generated by `7wd manifest` and committed as data/encoding/v<N>.json. Loading it checks the parts
Python relies on: the format tag, the input / policy / outcome sizes, a name for every index, and that each vector's
blocks tile it exactly (in order, no gaps, no overlaps).
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

FORMAT = "7wd-encoding-manifest"

REPO_ROOT = Path(__file__).resolve().parents[2]


class ManifestError(ValueError):
    """The manifest is malformed or doesn't match what Python expects."""


@dataclass(frozen=True)
class Block:
    name: str
    offset: int
    size: int


@dataclass(frozen=True)
class Manifest:
    version: int
    input_size: int
    policy_size: int
    outcome_classes: tuple[str, ...]
    input_blocks: tuple[Block, ...]
    policy_blocks: tuple[Block, ...]
    input_names: tuple[str, ...]
    policy_names: tuple[str, ...]
    path: Path | None = None

    @property
    def outcome_size(self) -> int:
        return len(self.outcome_classes)


def default_manifest_path(version: int = 1) -> Path:
    """The committed manifest for an Encoding version: <repo>/data/encoding/v<version>.json."""
    return REPO_ROOT / "data" / "encoding" / f"v{version}.json"


def load_manifest(path: str | Path | None = None) -> Manifest:
    path = Path(path) if path is not None else default_manifest_path()
    with open(path, encoding="utf-8") as f:
        raw = json.load(f)
    manifest = parse_manifest(raw)
    return Manifest(**{**manifest.__dict__, "path": path})


def parse_manifest(raw: dict) -> Manifest:
    if raw.get("format") != FORMAT:
        raise ManifestError(f"not an Encoding manifest (format {raw.get('format')!r}, expected {FORMAT!r})")
    version = raw.get("version")
    if not isinstance(version, int) or version < 1:
        raise ManifestError(f"bad Encoding version {version!r}")

    input_size, input_blocks, input_names = _vector(raw, "input")
    policy_size, policy_blocks, policy_names = _vector(raw, "policy")

    heads = raw.get("heads", {})
    if heads.get("policy", {}).get("size") != policy_size:
        raise ManifestError("heads.policy.size differs from policy.size")
    if heads.get("value", {}).get("size") != 1:
        raise ManifestError("heads.value.size must be 1")
    outcome = heads.get("outcome", {})
    classes = outcome.get("classes")
    if not isinstance(classes, list) or not classes or len(set(classes)) != len(classes):
        raise ManifestError("heads.outcome.classes must be a non-empty list of distinct names")
    if outcome.get("size", len(classes)) != len(classes):
        raise ManifestError("heads.outcome.size differs from the number of classes")

    return Manifest(
        version=version,
        input_size=input_size,
        policy_size=policy_size,
        outcome_classes=tuple(classes),
        input_blocks=input_blocks,
        policy_blocks=policy_blocks,
        input_names=input_names,
        policy_names=policy_names,
    )


def _vector(raw: dict, key: str) -> tuple[int, tuple[Block, ...], tuple[str, ...]]:
    section = raw.get(key)
    if not isinstance(section, dict):
        raise ManifestError(f"missing {key!r} section")
    size = section.get("size")
    if not isinstance(size, int) or size < 1:
        raise ManifestError(f"{key}.size must be a positive integer")

    blocks = tuple(Block(b["name"], b["offset"], b["size"]) for b in section.get("blocks", []))
    expected = 0
    for b in blocks:
        if b.size < 1:
            raise ManifestError(f"{key} block {b.name!r} has size {b.size}")
        if b.offset != expected:
            raise ManifestError(f"{key} block {b.name!r} starts at {b.offset}, expected {expected} (blocks must tile)")
        expected += b.size
    if expected != size:
        raise ManifestError(f"{key} blocks cover {expected} entries but {key}.size is {size}")

    names = tuple(section.get("names", []))
    if len(names) != size:
        raise ManifestError(f"{key} has {len(names)} names for {size} entries")
    if len(set(names)) != size:
        raise ManifestError(f"{key} names are not unique")
    return size, blocks, names
